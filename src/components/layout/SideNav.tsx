export function SideNav() {
  const location = useLocation()
  const navigate = useNavigate()
  const settings = useStore((s) => s.settings)

  const isActive = (path: string) =>
    path === '/home'
      ? location.pathname === '/home' || location.pathname === '/'
      : location.pathname.startsWith(path)

  return (
    <aside className="hidden md:flex flex-col w-56 bg-white border-r border-gray-100 min-h-svh sticky top-0">
      {/* Logo */}
      <div className="px-5 py-5 border-b border-gray-100">
        <div className="flex items-center gap-2.5">
          <div className="w-8 h-8 rounded-xl bg-gradient-to-br from-brand-500 to-accent-500 flex items-center justify-center text-white font-bold text-sm">
            ✦
          </div>
          <div>
            <div className="font-bold text-gray-900 text-sm leading-tight">MySheet</div>
            <div className="text-xs text-gray-400">{settings.companyName || 'マイブランド'}</div>
          </div>
        </div>
      </div>

      {/* Nav items */}
      <nav className="flex-1 px-3 py-4 space-y-1">
        {items.map((item) => {
          const active = isActive(item.path)
          return (
            <button
              key={item.path}
              type="button"
              onClick={() => navigate(item.path)}
              className={`w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition-all text-left
                ${active
                  ? 'bg-brand-50 text-brand-700'
                  : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900'
                }`}
            >
              <span className={active ? 'text-brand-600' : 'text-gray-400'}>
                {item.icon}
              </span>
              {item.label}
            </button>
          )
        })}
      </nav>

      {/* User */}
      <div className="px-4 py-4 border-t border-gray-100">
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-full bg-gradient-to-br from-brand-400 to-accent-400 flex items-center justify-center text-white text-xs font-bold flex-shrink-0">
            {settings.displayName?.charAt(0) || 'U'}
          </div>
          <div className="min-w-0">
            <div className="text-xs font-semibold text-gray-900 truncate">{settings.displayName}</div>
            <div className="text-xs text-gray-400 truncate">{settings.email}</div>
          </div>
        </div>
      </div>
    </aside>
  )
}
