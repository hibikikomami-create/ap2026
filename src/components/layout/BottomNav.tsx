export function BottomNav() {
  const location = useLocation()
  const navigate = useNavigate()

  const isActive = (matchPrefix: string) => location.pathname.startsWith(matchPrefix)

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-40 bg-white border-t border-slate-200">
      <div className="flex items-center justify-around max-w-lg mx-auto">
        {items.map((item) => {
          const active = isActive(item.matchPrefix)
          return (
            <button
              key={item.path}
              type="button"
              onClick={() => navigate(item.path)}
              className={`flex flex-col items-center gap-1 px-4 py-2.5 flex-1 transition-colors
                ${active ? 'text-brand-600' : 'text-slate-400 hover:text-slate-600'}`}
            >
              {item.icon}
              <span className="text-[10px] font-medium">{item.label}</span>
            </button>
          )
        })}
      </div>
    </nav>
  )
}
